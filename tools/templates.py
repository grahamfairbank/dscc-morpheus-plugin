#!/usr/bin/env python3
"""Builds src/main/resources/renderer/hbs/dscc-*.hbs from tools/templates/*.txt.

Each tab template = shared style + shared state notes + the tab's body + shared footer. The body opens the
tab's main {{#if isX}} block; this script closes it after the footer. Run after editing any .txt file.
"""
import os
here = os.path.dirname(os.path.abspath(__file__))
t = lambda n: open(os.path.join(here, "templates", n)).read()
out_dir = os.path.join(here, "..", "src", "main", "resources", "renderer", "hbs")
for name, hint in (("cluster", "cluster tab"), ("host", "hypervisor host tab"), ("guest", "VM (server and instance) tab")):
    html = ('{{!-- dscc-morpheus "HPE Storage" %s: read-only, no scripts. Generated by tools/templates.py. --}}\n' % hint
            + '<div class="dscc-morpheus dscc-morpheus-%s">\n' % name + t("_style.txt") + "\n" + t("_states.txt") + "\n"
            + t("_%s.txt" % name) + "\n" + t("_foot.txt") + "{{/if}}\n</div>\n")
    open(os.path.join(out_dir, "dscc-%s.hbs" % name), "w").write(html)
    print("wrote dscc-%s.hbs" % name)
